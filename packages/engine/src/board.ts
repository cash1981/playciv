const withoutPiece = (pieces: readonly BoardPiece[], pieceId: string): BoardPiece[] =>
  pieces.filter((piece) => piece.id !== pieceId)

const insertAt = (
  pieces: readonly BoardPiece[],
  index: number,
  piece: BoardPiece,
): BoardPiece[] => {
  const next = [...pieces]
  next.splice(Math.min(Math.max(index, 0), next.length), 0, piece)
  return next
}

/** Applies one change, moving the board forwards in time. */
export function applyChange(
  pieces: readonly BoardPiece[],
  change: BoardChange,
): readonly BoardPiece[] {
  switch (change.kind) {
    case 'place':
      return change.onTop ? [...pieces, change.piece] : [change.piece, ...pieces]
    case 'remove':
      return withoutPiece(pieces, change.piece.id)
    case 'move': {
      const piece = pieces.find((candidate) => candidate.id === change.pieceId)
      if (piece === undefined) return pieces
      return [...withoutPiece(pieces, piece.id), { ...piece, x: change.to.x, y: change.to.y }]
    }
    case 'rotate':
      return pieces.map((piece) =>
        piece.id === change.pieceId ? { ...piece, rotation: change.to } : piece,
      )
    case 'reorder': {
      const piece = pieces.find((candidate) => candidate.id === change.pieceId)
      if (piece === undefined) return pieces
      const rest = withoutPiece(pieces, piece.id)
      return change.toTop ? [...rest, piece] : [piece, ...rest]
    }
    case 'clear':
      return []
  }
}

/** Applies the inverse of one change, moving the board backwards in time. */
export function revertChange(
  pieces: readonly BoardPiece[],
  change: BoardChange,
): readonly BoardPiece[] {
  switch (change.kind) {
    case 'place':
      return withoutPiece(pieces, change.piece.id)
    case 'remove':
      return insertAt(pieces, change.index, change.piece)
    case 'move': {
      const piece = pieces.find((candidate) => candidate.id === change.pieceId)
      if (piece === undefined) return pieces
      return insertAt(withoutPiece(pieces, piece.id), change.fromIndex, {
        ...piece,
        x: change.from.x,
        y: change.from.y,
      })
    }
    case 'rotate':
      return pieces.map((piece) =>
        piece.id === change.pieceId ? { ...piece, rotation: change.from } : piece,
      )
    case 'reorder': {
      const piece = pieces.find((candidate) => candidate.id === change.pieceId)
      if (piece === undefined) return pieces
      return insertAt(withoutPiece(pieces, piece.id), change.fromIndex, piece)
    }
    case 'clear':
      return change.pieces
  }
}

/**
 * The pieces as they stood after `step` changes. Step 0 is the empty board
 * the game started from; `history.length` is the present.
 *
 * Replaying from scratch is cheap because the board is small, and it avoids
 * keeping a snapshot per change.
 */
export function piecesAtStep(
  history: readonly BoardHistoryEntry[],
  step: number,
): readonly BoardPiece[] {
  let pieces: readonly BoardPiece[] = []
  for (const entry of history.slice(0, Math.max(0, Math.min(step, history.length)))) {
    pieces = applyChange(pieces, entry.change)
  }
  return pieces
}
