/**
 * Keeps a piece inside the surface. Half of it may hang over the edge, so a
 * marker can sit in the margin without disappearing.
 */
export function clampToBoard(
  board: Board,
  x: number,
  y: number,
  width: number,
  height: number,
): readonly [x: number, y: number] {
  const clamp = (value: number, max: number): number => Math.min(Math.max(value, 0), max)
  return [
    clamp(Math.round(x), boardWidth(board) - width / 2),
    clamp(Math.round(y), boardHeight(board) - height / 2),
  ]
}

/** The square a piece sits in, by its centre. `null` when off the map. */
export function squareOf(board: Board, piece: BoardPiece): string | null {
  const column = Math.floor((piece.x + piece.width / 2) / board.squareSize)
  const row = Math.floor((piece.y + piece.height / 2 - mapTop(board)) / board.squareSize)
  if (column < 0 || column >= board.columns || row < 0 || row >= board.rows) return null
  return `${COLUMN_LABELS[column] ?? '?'}${row + 1}`
}

/** Where a piece is, in words: a culture space, a map square or a player's area. */
export function locationOf(
  board: Board,
  areas: readonly BoardArea[],
  piece: BoardPiece,
): string {
  const step = cultureStepOf(board, piece)
  if (step !== null) return `culture ${step}`

  const square = squareOf(board, piece)
  if (square !== null) return square

  const area = areaAt(areas, piece.x + piece.width / 2, piece.y + piece.height / 2)
  if (area !== undefined) return `${area.username}'s area`

  return 'off the board'
}

export function findPiece(board: Board, pieceId: string): BoardPiece | undefined {
  return board.pieces.find((piece) => piece.id === pieceId)
}

