/**
 * The board.
 *
 * Replaces the Google Presentation hack: the old system stored a link to a
 * slide in `PBF.mapLink` and let a moderator move pieces around by hand.
 *
 * The geometry comes from `Civilization/Moderator/4v4 Map Template.pptx`:
 * 16 x 16 squares labelled A-P and 1-16, assembled from 4 x 4 map tiles of
 * 375 x 375 pixels. That makes a square 375 / 4 ~ 94 pixels, which is exactly
 * the size of the city, building and city-state pieces in the same folder.
 *
 * Pieces sit at free pixel coordinates rather than snapping to squares. That is
 * how the PowerPoint template was used, and it is what makes it possible to
 * stack several pieces in one square or park one half outside the edge.
 *
 * Below the map is a band of player areas, one per player. Dropping a piece
 * there tidies it into the next free slot, so a pile of collected huts reads as
 * a row rather than a heap.
 */

import boardAssets from '../data/board-assets.json' with { type: 'json' }

/** Edge length of one square, in the board's own coordinate system. */
export const SQUARE_SIZE = 94

/** A map tile covers 4 x 4 squares. */
export const TILE_SQUARES = 4

/** 4 x 4 map tiles, as in the four-player template. */
export const DEFAULT_COLUMNS = 16
export const DEFAULT_ROWS = 16

/** Height of the player-area band, in squares. */
export const DEFAULT_AREA_ROWS = 4

/** Blank space between the map and the player areas, in squares. */
export const AREA_GAP_SQUARES = 1

/** Blank space between the culture track and the map, in squares. */
export const CULTURE_GAP_SQUARES = 1

/** Room for the name written across the top of a player area, in pixels. */
export const AREA_LABEL_HEIGHT = 26

/** Column labels from the template: A through P. */
export const COLUMN_LABELS = Array.from({ length: DEFAULT_COLUMNS }, (_, index) =>
  String.fromCharCode(65 + index),
)

export type BoardAssetCategory =
  | 'figure'
  | 'resource'
  | 'marker'
  | 'city'
  | 'building'
  /** The civilizations' starting tiles, one per civ. */
  | 'civtile'
  /** The numbered exploration tiles, plus the tile back. */
  | 'tile'
  /** Leader portraits, which mark a player's place on the culture track. */
  | 'leader'

/** Pieces can face four ways. Degrees, clockwise. */
export type Rotation = 0 | 90 | 180 | 270

export const ROTATIONS: readonly Rotation[] = [0, 90, 180, 270]

export function nextRotation(rotation: Rotation, clockwise = true): Rotation {
  const index = ROTATIONS.indexOf(rotation)
  const step = clockwise ? 1 : ROTATIONS.length - 1
  return ROTATIONS[(index + step) % ROTATIONS.length] as Rotation
}

/** A kind of piece that can be put on the board, taken from the images on disk. */
export interface BoardAsset {
  /** Stable key, for example "figures/redarmy". */
  readonly id: string
  readonly category: BoardAssetCategory
  /** Path under the client's /board/, for example "figures/redarmy.png". */
  readonly path: string
  readonly label: string
  readonly width: number
  readonly height: number
}

/** The culture track backdrop: a path under /board/ and its natural size. */
export interface CultureTrackImage {
  readonly path: string
  readonly width: number
  readonly height: number
}

interface BoardAssetFile {
  readonly cultureTrack: CultureTrackImage
  readonly assets: readonly BoardAsset[]
}

/** The culture track image, drawn across the top of the board. */
export const CULTURE_TRACK: CultureTrackImage = (boardAssets as BoardAssetFile).cultureTrack

/**
 * Every known kind of piece, generated by `tools/board-assets.ps1` from the
 * images in `Civilization/Moderator`. The manifest lives in the engine rather
 * than the client because the server has to be able to reject a piece pointing
 * at an unknown file.
 */
export const BOARD_ASSETS: readonly BoardAsset[] = (boardAssets as BoardAssetFile).assets

const ASSETS_BY_ID = new Map(BOARD_ASSETS.map((asset) => [asset.id, asset]))

export function findBoardAsset(assetId: string): BoardAsset | undefined {
  return ASSETS_BY_ID.get(assetId)
}

export function boardAssetsByCategory(category: BoardAssetCategory): readonly BoardAsset[] {
  return BOARD_ASSETS.filter((asset) => asset.category === category)
}

/** A piece lying on the board. */
export interface BoardPiece {
  readonly id: string
  readonly assetId: string
  /** Copied from the manifest on placement so the client needs no lookup. */
  readonly path: string
  readonly label: string
  readonly category: BoardAssetCategory
  /** Left and top edge in board coordinates. */
  readonly x: number
  readonly y: number
  readonly width: number
  readonly height: number
  /**
   * Rotation clockwise. Map tiles carry an arrow showing which way the tile
   * goes, so they have to turn. Every piece can turn, for consistency.
   */
  readonly rotation: Rotation
  /** Who put it there. Anyone may move it afterwards. */
  readonly placedBy: string | null
}

