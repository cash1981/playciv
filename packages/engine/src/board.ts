/** The five player colours the leader artwork comes in. */
const LEADER_COLOURS = new Set(['blue', 'green', 'purple', 'red', 'yellow'])

/**
 * The leader marker for a civilization in a player's colour, or undefined when
 * either is unknown. White has no leader artwork — it is the barbarian colour
 * and no player takes it.
 */
export function leaderAssetId(civName: string, color: string): string | undefined {
  const leader = LEADER_BY_CIV[civName]
  const colour = color.toLowerCase()
  if (leader === undefined || !LEADER_COLOURS.has(colour)) return undefined
  return `leaders/${leader}_${colour}`
}

/**
 * The number on a Tile card to the file name of its image.
 *
 * The files are called tile01 through tile14, then tile15a through tile21a,
 * then tile22b through tile25b, and finally Tile26b and Tile27b. The suffixes
 * separate the expansions, so the lookup goes by the number in the name.
 */
const TILE_BY_NUMBER = new Map<number, string>(
  BOARD_ASSETS.filter((asset) => asset.category === 'tile')
    .map((asset) => {
      const digits = /(\d+)/.exec(asset.id)
      return digits === null ? null : ([Number(digits[1]), asset.id] as const)
    })
    .filter((entry): entry is readonly [number, string] => entry !== null),
)

export function tileAssetIdForNumber(tileNumber: number): string | undefined {
  return TILE_BY_NUMBER.get(tileNumber)
}

