/** One player's own space below the map. */
export interface BoardArea {
  readonly playerId: string
  readonly username: string
  readonly color: string | null
  readonly x: number
  readonly y: number
  readonly width: number
  readonly height: number
}

/** The bit of an area that holds pieces, below the name. */
export const areaSlotRegion = (
  area: BoardArea,
): { readonly x: number; readonly y: number; readonly width: number; readonly height: number } => ({
  x: area.x,
  y: area.y + AREA_LABEL_HEIGHT,
  width: area.width,
  height: area.height - AREA_LABEL_HEIGHT,
})

/** Just enough of a player to lay out their area. */
export interface AreaPlayer {
  readonly playerId: string
  readonly username: string
  readonly color: string | null
  readonly playernumber: number
}

/**
 * Lays the players out in a band below the map, in player-number order, one
 * equal-width area each. Derived rather than stored, so it cannot drift out of
 * step when someone joins or withdraws.
 */
export function playerAreas(
  board: Board,
  players: readonly AreaPlayer[],
): readonly BoardArea[] {
  if (players.length === 0) return []

  const gutter = 8
  const top = areaBandTop(board)
  const height = board.areaRows * board.squareSize
  const total = boardWidth(board)
  const width = (total - gutter * (players.length - 1)) / players.length

  return [...players]
    .sort((a, b) => a.playernumber - b.playernumber || a.username.localeCompare(b.username))
    .map((player, index) => ({
      playerId: player.playerId,
      username: player.username,
      color: player.color,
      x: Math.round(index * (width + gutter)),
      y: top,
      width: Math.round(width),
      height,
    }))
}

/** The area a point falls inside, if any. */
export function areaAt(
  areas: readonly BoardArea[],
  x: number,
  y: number,
): BoardArea | undefined {
  return areas.find(
    (area) =>
      x >= area.x && x < area.x + area.width && y >= area.y && y < area.y + area.height,
  )
}

/**
 * The next free slot in a player area, read row by row.
 *
 * Pieces dropped in an area tidy themselves into a grid, so five collected huts
 * line up instead of piling on top of each other. Falls back to the drop point
 * when the area is full.
 */
export function nextFreeSlot(
  board: Board,
  area: BoardArea,
  pieces: readonly BoardPiece[],
  fallback: { readonly x: number; readonly y: number },
): readonly [x: number, y: number] {
  const region = areaSlotRegion(area)
  const slot = board.squareSize
  const columns = Math.max(1, Math.floor(region.width / slot))
  const rows = Math.max(1, Math.floor(region.height / slot))

  const taken = new Set(
    pieces
      .filter(
        (piece) =>
          piece.x >= region.x &&
          piece.x < region.x + region.width &&
          piece.y >= region.y &&
          piece.y < region.y + region.height,
      )
      .map((piece) => {
        const column = Math.round((piece.x - region.x) / slot)
        const row = Math.round((piece.y - region.y) / slot)
        return `${column},${row}`
      }),
  )

  for (let row = 0; row < rows; row++) {
    for (let column = 0; column < columns; column++) {
      if (!taken.has(`${column},${row}`)) {
        return [region.x + column * slot, region.y + row * slot]
      }
    }
  }
  return [fallback.x, fallback.y]
}

