/**
 * One change to the pieces on the board.
 *
 * Each variant carries exactly what is needed to apply it forwards and to take
 * it back, so the whole game can be stepped through and any change undone. A
 * generic before/after diff was tempting but would record the entire stack
 * every time a piece is brought to the front.
 */
export type BoardChange =
  /** `onTop` is false for map tiles, which slide underneath everything else. */
  | { readonly kind: 'place'; readonly piece: BoardPiece; readonly onTop: boolean }
  | { readonly kind: 'remove'; readonly piece: BoardPiece; readonly index: number }
  | {
      readonly kind: 'move'
      readonly pieceId: string
      readonly from: { readonly x: number; readonly y: number }
      readonly to: { readonly x: number; readonly y: number }
      /** Where it sat in the stack before; moving also brings it to the top. */
      readonly fromIndex: number
    }
  | {
      readonly kind: 'rotate'
      readonly pieceId: string
      readonly from: Rotation
      readonly to: Rotation
    }
  | {
      readonly kind: 'reorder'
      readonly pieceId: string
      readonly fromIndex: number
      readonly toTop: boolean
    }
  | { readonly kind: 'clear'; readonly pieces: readonly BoardPiece[] }

export interface BoardHistoryEntry {
  readonly id: string
  /** ISO timestamp, supplied by the caller since the engine stays pure. */
  readonly at: string | null
  readonly playerId: string
  readonly username: string
  /** Ready to show in a list: "cash1981 moved Red army from E4 to H8". */
  readonly description: string
  readonly change: BoardChange
  /**
   * How many game-log entries existed once this change was made. Stepping back
   * through history uses it to trim the log to what was known at the time.
   */
  readonly logLength: number
}

/**
 * The board. The order of `pieces` IS the stacking order: the last element is
 * drawn on top. That removes the need for a z-index, and "bring to front" is
 * just a move to the end of the list.
 */
export interface Board {
  readonly columns: number
  readonly rows: number
  readonly squareSize: number
  /** Height of the player-area band below the map, in squares. */
  readonly areaRows: number
  readonly pieces: readonly BoardPiece[]
  readonly history: readonly BoardHistoryEntry[]
}

export function createBoard(
  columns = DEFAULT_COLUMNS,
  rows = DEFAULT_ROWS,
  areaRows = DEFAULT_AREA_ROWS,
): Board {
  return { columns, rows, squareSize: SQUARE_SIZE, areaRows, pieces: [], history: [] }
}

export const boardWidth = (board: Board): number => board.columns * board.squareSize
/** Height of the map itself, not counting the track or the player areas. */
export const mapHeight = (board: Board): number => board.rows * board.squareSize

/**
 * Height of the culture track band. The track image is drawn across the full
 * width of the map, so its height follows from its own aspect.
 */
export const cultureTrackHeight = (board: Board): number =>
  Math.round((boardWidth(board) * CULTURE_TRACK.height) / CULTURE_TRACK.width)

/** Top edge of the map. The culture track sits above it. */
export const mapTop = (board: Board): number =>
  cultureTrackHeight(board) + CULTURE_GAP_SQUARES * board.squareSize

/** Top edge of the player-area band. */
export const areaBandTop = (board: Board): number =>
  mapTop(board) + mapHeight(board) + AREA_GAP_SQUARES * board.squareSize

/** Full height of the drag surface: track, map and player areas, with gaps. */
export const boardHeight = (board: Board): number =>
  areaBandTop(board) + board.areaRows * board.squareSize

// ---------------------------------------------------------------------------
// The culture track
// ---------------------------------------------------------------------------

/**
 * The spaces of the culture track, measured off the artwork by finding the dark
 * divider columns in `DoC/PBF Modding Material/culture track.png`.
 *
 * There are 27 spaces between Start and Culture Victory, in four sections of
 * 7, 7, 7 and 6 — one per culture event — separated by a wide pillar. Within a
 * section the spaces are even, so each is given as the pixel span of its
 * section in the source image and divided up.
 *
 * Neither Java nor the AngularJS app had a culture track. It is a marker only:
 * nothing here enforces what it costs to advance or what happens at a
 * threshold, because those rules are not in the ported source.
 */
const CULTURE_SECTIONS: readonly { readonly from: number; readonly to: number; readonly cells: number }[] = [
  { from: 116, to: 907, cells: 7 },
  { from: 936, to: 1725, cells: 7 },
  { from: 1753, to: 2540, cells: 7 },
  { from: 2569, to: 3252, cells: 6 },
]

/** Spaces on the track, numbered 1 to 27. */
export const CULTURE_TRACK_CELLS = CULTURE_SECTIONS.reduce(
  (total, section) => total + section.cells,
  0,
)

/** Centre of each space as a fraction of the track image's width. */
const CULTURE_CELL_FRACTIONS: readonly number[] = CULTURE_SECTIONS.flatMap((section) => {
  const width = (section.to - section.from) / section.cells
  return Array.from(
    { length: section.cells },
    (_, index) => (section.from + (index + 0.5) * width) / CULTURE_TRACK.width,
  )
})

/** Bottom edge of the culture track band. */
export const cultureBandBottom = (board: Board): number => cultureTrackHeight(board)

/** Whether a point falls in the culture track band. */
export const inCultureBand = (board: Board, y: number): boolean =>
  y >= 0 && y < cultureBandBottom(board)

/**
 * Centre of one space, in board coordinates. `step` is 1-based, matching the
 * numbering players use when they say "I am on 12".
 */
export function cultureCellCenter(
  board: Board,
  step: number,
): { readonly x: number; readonly y: number } {
  const index = Math.min(Math.max(Math.round(step), 1), CULTURE_TRACK_CELLS) - 1
  const fraction = CULTURE_CELL_FRACTIONS[index] ?? 0
  return {
    x: Math.round(fraction * boardWidth(board)),
    y: Math.round(cultureTrackHeight(board) / 2),
  }
}

/** The space a piece sits on, by its centre, or null when off the track. */
export function cultureStepOf(board: Board, piece: BoardPiece): number | null {
  const centreY = piece.y + piece.height / 2
  if (!inCultureBand(board, centreY)) return null

  const centreX = (piece.x + piece.width / 2) / boardWidth(board)
  let best = 0
  let bestDistance = Number.POSITIVE_INFINITY
  for (const [index, fraction] of CULTURE_CELL_FRACTIONS.entries()) {
    const distance = Math.abs(fraction - centreX)
    if (distance < bestDistance) {
      bestDistance = distance
      best = index
    }
  }
  return best + 1
}

/**
 * Where a piece dropped on the culture track belongs: centred on the nearest
 * space. Markers already on that space are stepped down a row so several
 * players on the same space stay readable rather than hiding each other.
 */
export function cultureSlot(
  board: Board,
  piece: BoardPiece,
  x: number,
  y: number,
  others: readonly BoardPiece[],
): readonly [x: number, y: number] {
  const step = cultureStepOf(board, { ...piece, x, y }) ?? 1
  const centre = cultureCellCenter(board, step)
  const left = Math.round(centre.x - piece.width / 2)

  const band = cultureTrackHeight(board)
  const lanes = Math.max(1, Math.floor(band / piece.height))
  const sharing = others.filter(
    (other) => other.id !== piece.id && cultureStepOf(board, other) === step,
  ).length

  const lane = sharing % lanes
  const top = Math.round((band - lanes * piece.height) / 2 + lane * piece.height)
  return [left, top]
}

